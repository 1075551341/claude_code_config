def absolutize_pointers(text: str) -> str:
    return MASTER_PATH_RE.sub(lambda m: "`~/.claude/" + m.group(1) + "`", text)


def render_agents_md(version: str) -> str:
    claude_md = read_text(CLAUDE / "CLAUDE.md")
    core_md = read_text(CLAUDE / "rules" / "CORE.md")
    body = re.sub(r"^---\n.*?\n---\n", "", claude_md, count=1, flags=re.S)
    for pattern, repl in LINE_REWRITES:
        body = pattern.sub(repl, body)
    core = re.sub(r"^---\n.*?\n---\n", "", core_md, count=1, flags=re.S)
    text = (
        GENERATED_BANNER + "\n\n"
        + body.rstrip()
        + "\n" + CODEX_GATE_SECTION.rstrip() + "\n\n---\n\n"
        + "# 铁律与工程规范正文（= `~/.claude/rules/CORE.md` 全文内联）\n\n"
        + "> L0 必加载：Codex 没有 rules 引擎，铁律随本文件进入每次会话。正文只有一份，"
          "改动只在主干 `rules/CORE.md`，本段由生成器注入。\n\n"
        + absolutize_pointers(core).rstrip() + "\n\n"
        + "> 配置版本 " + version + " | 真源 " + rel(CLAUDE) + "\n"
    )
    return absolutize_pointers(text)


# ---------------------------------------------------------------- agents
FRONT_RE = re.compile(r"^---\n(.*?)\n---\n", re.S)
TOOLS_NOTE = "## 工具边界（投放自 agents/ frontmatter `tools:`）\n\n"


def parse_agent_md(path: Path) -> tuple:
    raw = read_text(path)
    match = FRONT_RE.match(raw)
    meta, body = {}, raw
    if match:
        meta, body = {}, raw[match.end():]
        for line in match.group(1).splitlines():
            if ":" in line and not line.startswith((" ", "#")):
                key, value = line.split(":", 1)
                meta[key.strip()] = value.strip()
    return meta, body.strip()


def toml_literal(text: str) -> str:
    if "'''" in text:
        return json.dumps(text)
    return "'''\n" + text.replace("\r\n", "\n").rstrip() + "\n'''"


def render_agent_toml(path: Path) -> str:
    meta, body = parse_agent_md(path)
    name = meta.get("name") or path.stem
    tools = meta.get("tools", "")
    if tools:
        body += "\n\n" + TOOLS_NOTE + "\n本角色授权工具：" + tools + "。清单外的写/执行操作一律不做。\n"
    lines = [
        "name = " + json.dumps(name, ensure_ascii=False),
        "description = " + json.dumps(meta.get("description", name), ensure_ascii=False),
        "developer_instructions = " + toml_literal(body),
    ]
    return "\n".join(lines) + "\n"


