# ---------------------------------------------------------------- hooks + config
def write_text(path: Path, text: str, changed: list, label: str, dry: bool) -> None:
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        print("  [up-to-date] " + label)
        return
    if dry:
        print("  [dry-run] " + label)
        changed.append(label)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    note(changed, label, rel(path))


def patch_config_toml(changed: list, dry: bool) -> None:
    path = CODEX / "config.toml"
    text = read_text(path)
    blocks = split_toml(text)
    kept = []
    dropped = []
    for header, body in blocks:
        name = table_name(header)
        if name in MCP_DROP:
            dropped.append(header)
            continue
        if name.startswith(HOOK_STATE_PREFIX) and CODEX_TRUST_MARK in name.replace("/", "\\"):
            # 只失效本仓库投放的 ~/.codex/hooks.json 信任项；插件自带 hook 的信任保留。
            dropped.append(header)
            continue
        if name in PLUGIN_OFF:
            new_body = [("enabled = false" if re.match(r"^\s*enabled\s*=", line) else line)
                        for line in body]
            if not any(re.match(r"^\s*enabled\s*=", line) for line in new_body):
                new_body = new_body + ["enabled = false"]
            if new_body != body:
                changed.append("plugin off: " + name)
            body = new_body
        if name == "shell_environment_policy.set":
            kept_body = [line for line in body
                         if not re.match(r"^\s*(" + "|".join(map(re.escape, ENV_DROP_KEYS)) + r")\s*=", line)]
            if len(kept_body) != len(body):
                changed.append("env secret removed from [shell_environment_policy.set]")
            body = kept_body
        kept.append((header, body))
    out = rebuild_toml(kept)
    if dropped:
        print("  dropped %d toml blocks:" % len(dropped))
        for header in dropped:
            print("    - " + header.strip())
    if out != text:
        write_text(path, out, changed, "config.toml", dry)
    else:
        print("  [up-to-date] config.toml")


def write_hooks_json(changed: list, dry: bool) -> None:
    raw = SNIPPET.read_text(encoding="utf-8")
    raw = raw.replace("{{CLAUDE_HOME}}", str(CLAUDE).replace("\\", "/"))
    raw = raw.replace("{{PYTHON}}", str(Path(sys.executable)).replace("\\", "/"))
    data = json.loads(raw)
    if "hooks" not in data:
        die("snippet missing hooks section")
    write_text(CODEX / "hooks.json",
               json.dumps(data, ensure_ascii=False, indent=2) + "\n",
               changed, "hooks.json", dry)


