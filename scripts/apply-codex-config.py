    (re.compile(r"用户显式指令 > CLAUDE\.md"), "用户显式指令 > AGENTS.md"),
    (re.compile(r">\s*CLAUDE\.md 为纯路由"), "> CLAUDE.md 为纯路由"),
    (re.compile(r"\b同步：`scripts/sync\.ps1`（cursor / qoder-cn / trae-cn / trae）"),
     "同步：`scripts/sync.ps1`（cursor / qoder-cn / trae-cn / trae）+ `scripts/apply-codex-config.py`（codex）"),
    (re.compile(r"不生成 `AGENTS\.md`（Codex/OpenCode 自管）"),
     "Codex 由 apply-codex-config.py 投放（AGENTS.md/agents/hooks 派生自本仓库）"),
    (re.compile(r"^\| L0\s+\| 本文件 \+ `~/.claude/rules/CORE\.md`", re.M),
     "| L0  | 本文件（已内联 `~/.claude/rules/CORE.md` 全文）"),
    (re.compile(r"^> 配置版本 "), "> 配置版本 v"),
