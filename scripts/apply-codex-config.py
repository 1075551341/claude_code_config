def rel(path: Path) -> str:
    return str(path)


def die(msg: str, code: int = 2) -> None:
    sys.stderr.write("apply-codex-config: " + msg + "\n")
    raise SystemExit(code)


def note(changed: list, label: str, detail: str = "") -> None:
    changed.append(label)
    print("  [OK] " + label + ((" -> " + detail) if detail else ""))


def read_text(path: Path) -> str:
    if not path.is_file():
        die("missing source " + rel(path))
    return path.read_text(encoding="utf-8-sig")


# ---------------------------------------------------------------- TOML helpers
HEADER_RE = re.compile(r"^\[\[?[^\[]")


def split_toml(text: str) -> list:
    """按 top-level table header 切块 -> [(header, [body lines]), ...]；前导块 header 为 ""。"""
    blocks = [("", [])]
    for line in text.splitlines():
        if HEADER_RE.match(line):
            blocks.append((line.rstrip(), []))
        else:
            blocks[-1][1].append(line)
    return blocks


def rebuild_toml(blocks: list) -> str:
    out = []
    for header, body in blocks:
        if header:
            out.append(header)
        out.extend(body)
    return "\n".join(out).rstrip() + "\n"


def table_name(header: str) -> str:
    match = re.match(r"^\[([^\]]+)\]", header.strip())
    return match.group(1).strip() if match else ""


