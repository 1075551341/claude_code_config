def is_link(path: Path) -> bool:
    """junction/symlink 判定必须用 lstat：Path.stat() 会穿透 reparse point 看到目标目录。"""
    if not (path.exists() or is_link_raw(path)):
        return False
    try:
        st = os.stat(str(path), follow_symlinks=False)
    except OSError:
        return False
    return bool(getattr(st, "st_reparse_tag", 0)) or path.is_symlink()


def is_link_raw(path: Path) -> bool:
    try:
        return bool(os.stat(str(path), follow_symlinks=False).st_reparse_tag)
    except OSError:
        return False


def make_junction(link: Path, target_dir: Path) -> bool:
    if link.exists() or is_link(link):
        if is_link(link):
            try:
                if Path(os.path.realpath(link)) == target_dir:
                    return True
            except OSError:
                pass
            if link.is_symlink():
                os.unlink(str(link))
            else:
                # junction: os.rmdir 只摘链接，绝不进入目标目录（cmd rmdir 带尾分隔符会删目标内容）
                os.rmdir(str(link))
    proc = subprocess.run(
        ["cmd.exe", "/c", "mklink", "/J", str(link), str(target_dir)],
        capture_output=True, text=True, encoding="utf-8", errors="replace")
    return proc.returncode == 0 and (is_link(link) or link.is_dir())


def sync_skills(changed: list, dry: bool) -> int:
    master = sorted(p.name for p in (CLAUDE / "skills").iterdir() if p.is_dir())
    if not master:
        die("no master skills found")
    ok = skipped = failed = 0
    for name in master:
        src = CLAUDE / "skills" / name
        dst = AGENTS_SKILLS / name
        if name in SKILL_PREFER_CODEX:
            if dst.exists() or is_link(dst):
                if dry:
                    print("  [dry-run] retire duplicate skill " + name + " (Codex built-in wins)")
                else:
                    BACKUP.mkdir(parents=True, exist_ok=True)
                    dest = BACKUP / "agents-skills" / name
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    if is_link(dst) and not dst.is_dir():
                        os.rmdir(str(dst)) if not dst.is_symlink() else os.unlink(str(dst))
                        note([], "retired duplicate skill link", name)
                    else:
                        shutil.move(str(dst), str(dest))
                        note([], "retired duplicate skill", name + " -> " + rel(dest))
            continue
        if is_link(dst):
            skipped += 1
            continue
        if dry:
            print("  [dry-run] junction " + name)
            ok += 1
            continue
        if dst.is_dir():
            BACKUP.mkdir(parents=True, exist_ok=True)
            shutil.move(str(dst), str(BACKUP / "agents-skills" / name))
        dst.parent.mkdir(parents=True, exist_ok=True)
        if make_junction(dst, src):
            ok += 1
        else:
            failed += 1
            print("  [FAIL] junction " + name)
    print("  skills: junction=%d already=%d failed=%d backup=%s"
          % (ok, skipped, failed, rel(BACKUP) if ok else "-"))
    if failed:
        changed.append("skills junction incomplete")
    else:
        changed.append("skills junction")
    return failed


def sync_commands(changed: list, dry: bool) -> None:
    commands = sorted((CLAUDE / "commands").glob("*.md"))
    if not commands:
        die("no master commands found")
    count = 0
    for cmd in commands:
        meta, body = parse_agent_md(cmd)
        name = "source-command-" + cmd.stem
        desc = meta.get("description") or ("Codex skill migrated from /" + cmd.stem)
        text = (
            "---\n"
            + "name: \"" + name + "\"\n"
            + "description: \"" + desc.replace('"', "'") + "\"\n"
            + "---\n\n"
            + "# " + name + "\n\n"
            + "> 派生自 `~/.claude/commands/" + cmd.name + "`（薄壳：正文在对应 skill，勿在此复制）。"
              "由 `scripts/apply-codex-config.py` 生成。\n\n"
            + "Use this skill when the user asks to run the migrated source command `" + cmd.stem + "`.\n\n"
            + "## Command Template\n\n" + body + "\n"
        )
        dst = AGENTS_SKILLS / name / "SKILL.md"
        if dry:
            print("  [dry-run] command skill " + name)
            continue
        write_text(dst, text, changed, "command skill " + name, dry)
        count += 1
    print("  command skills: %d from %d master commands" % (count, len(commands)))


def sync_quality_gates(changed: list, dry: bool) -> None:
    path = CLAUDE / "config" / "quality_gates.json"
    data = json.loads(read_text(path))
    gate = data.get("quality_gates", {}).get("impact_manifest_gate")
    if not isinstance(gate, dict):
        return
    platforms = [str(x) for x in (gate.get("platforms") or [])]
    if "codex" in platforms:
        print("  [up-to-date] quality_gates platforms")
        return
    gate["platforms"] = platforms + ["codex"]
    write_text(path, json.dumps(data, ensure_ascii=False, indent=2) + "\n",
               changed, "quality_gates +codex", dry)


def prune_stale(changed: list, dry: bool) -> None:
    live = {p.stem for p in master_agents()}
    agents_dir = CODEX / "agents"
    removed = []
    for toml in sorted(agents_dir.glob("*.toml")) if agents_dir.is_dir() else []:
        if toml.stem not in live or toml.stem in STALE_AGENTS:
            removed.append(toml.name)
            if not dry:
                BACKUP.mkdir(parents=True, exist_ok=True)
                shutil.move(str(toml), str(BACKUP / toml.name))
    if removed:
        note(changed, "pruned stale agents", ", ".join(removed))
    fork = CODEX / "hooks"
    if fork.is_dir() and not is_link(fork):
        if dry:
            print("  [dry-run] retire forked hook dir ~/.codex/hooks")
        else:
            BACKUP.mkdir(parents=True, exist_ok=True)
            shutil.move(str(fork), str(BACKUP / "codex-hooks-fork"))
            note(changed, "retired forked hook dir", rel(fork) + " -> " + rel(BACKUP))


# ---------------------------------------------------------------- agents sync
def read_version() -> str:
    manifest = CLAUDE / "MANIFEST.yaml"
    if manifest.is_file():
        for line in manifest.read_text(encoding="utf-8-sig").splitlines():
            match = re.match(r"^version:\s*[\x22']?([0-9][^\s'\x22]*)", line.strip())
            if match:
                return match.group(1)
    return "unknown"


def sync_agents(changed: list, dry: bool) -> None:
    out_dir = CODEX / "agents"
    count = 0
    for md in master_agents():
        toml_path = out_dir / (md.stem + ".toml")
        text = render_agent_toml(md)
        if dry:
            print("  [dry-run] agent " + md.stem)
            count += 1
            continue
        write_text(toml_path, text, changed, "agent " + md.stem, dry)
        count += 1
    print("  agents: %d rendered from master" % count)


def check_skills() -> list:
    """主干技能须经 junction 单一真源抵达 Codex；实体拷贝即漂移（--check 用）。"""
    drift = []
    if not AGENTS_SKILLS.is_dir():
        return ["~/.agents/skills missing (run --skills)"]
    import hashlib

    def digest(path: Path) -> str:
        return hashlib.sha256(path.read_bytes()).hexdigest()

    for src in sorted(x for x in (CLAUDE / "skills").iterdir() if x.is_dir()):
        link = AGENTS_SKILLS / src.name
        if src.name in SKILL_PREFER_CODEX:
            if link.exists() or is_link(link):
                drift.append("skills/" + src.name + " (duplicates Codex built-in)")
            continue
        if not (link / "SKILL.md").is_file():
            drift.append("skills/" + src.name + " (missing)")
            continue
        if not is_link(link):
            drift.append("skills/" + src.name + " (entity copy, not junction -> will drift)")
        elif digest(link / "SKILL.md") != digest(src / "SKILL.md"):
            drift.append("skills/" + src.name + " (content differs from master)")
    for cmd in sorted((CLAUDE / "commands").glob("*.md")):
        gen = AGENTS_SKILLS / ("source-command-" + cmd.stem) / "SKILL.md"
        if not gen.is_file():
            drift.append("skills/source-command-" + cmd.stem + " (command skill missing)")
        elif "apply-codex-config.py" not in gen.read_text(encoding="utf-8"):
            drift.append("skills/source-command-" + cmd.stem + " (hand-edited derived file)")
    return drift


# ---------------------------------------------------------------- main
def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--skills", action="store_true",
                        help="junction 主干技能 + 重生成 source-command-*（需写 ~/.agents）")
    parser.add_argument("--prune", action="store_true",
                        help="备份并移除废弃 agent 与 ~/.codex/hooks 分叉")
    parser.add_argument("--check", action="store_true",
                        help="只比对生成物是否与真源一致，不写入")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    if not CLAUDE.is_dir():
        die("master config repo missing: " + rel(CLAUDE))
    changed: list = []
    version = read_version()
    print("apply-codex-config | master=%s v%s | target=%s%s"
          % (rel(CLAUDE), version, rel(CODEX), " (check)" if args.check else ""))

    want_agents = render_agents_md(version)
    want_hooks = (SNIPPET.read_text(encoding="utf-8")
                  .replace("{{CLAUDE_HOME}}", str(CLAUDE).replace("\\", "/"))
                  .replace("{{PYTHON}}", str(Path(sys.executable)).replace("\\", "/")))
    hooks_obj = json.loads(want_hooks)
    want_hooks_text = json.dumps(hooks_obj, ensure_ascii=False, indent=2) + "\n"

    if args.check:
        drift = []
        if (CODEX / "AGENTS.md").is_file() and (CODEX / "AGENTS.md").read_text(encoding="utf-8") != want_agents:
            drift.append("AGENTS.md")
        if (CODEX / "hooks.json").is_file() and (CODEX / "hooks.json").read_text(encoding="utf-8") != want_hooks_text:
            drift.append("hooks.json")
        for md in master_agents():
            toml_path = CODEX / "agents" / (md.stem + ".toml")
            if not toml_path.is_file():
                drift.append("agents/" + md.stem + ".toml (missing)")
            elif toml_path.read_text(encoding="utf-8") != render_agent_toml(md):
                drift.append("agents/" + md.stem + ".toml")
        for name in MCP_DROP:
            if re.search(r"^\[" + re.escape(name) + r"\]", (CODEX / "config.toml").read_text(encoding="utf-8"), re.M):
                drift.append(name + " (duplicate of plugin)")
        if AGENTS_SKILLS.is_dir():
            drift.extend(check_skills())
        if drift:
            print("  DRIFT:\n    " + "\n    ".join(drift))
            return 1
        print("  in sync")
        return 0

    write_text(CODEX / "AGENTS.md", want_agents, changed, "AGENTS.md", args.dry_run)
    write_hooks_json(changed, args.dry_run)
    patch_config_toml(changed, args.dry_run)
    sync_agents(changed, args.dry_run)
    if args.skills:
        failed = sync_skills(changed, args.dry_run)
        sync_commands(changed, args.dry_run)
        if failed:
            return 2
    if args.prune:
        prune_stale(changed, args.dry_run)
    sync_quality_gates(changed, args.dry_run)
    print("  done: " + (", ".join(dict.fromkeys(changed)) if changed else "no change"))
    return 0


